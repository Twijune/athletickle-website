// Copies the legal documents from Athletickle PK into the website, so the
// app and the site publish one text. Run it after editing the apps' legal.ts /
// legal.fi.ts (or company.ts), then rebuild:
//
//   node scripts/sync-legal.mjs [path to the PK repo]   (default ../ParkourTrainingApp)
//
// STR ships the same files except its own §4 / health passages; the site's
// Terms §4 combines both editions in src/data/legal/site.ts.
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const app = resolve(root, process.argv[2] ?? '../ParkourTrainingApp')

const HEADER =
  '// GENERATED by scripts/sync-legal.mjs from Athletickle PK - do not edit here.\n' +
  '// Edit the apps (PK and STR) and re-run the script.\n\n'

// [source, target, [from, to] rewrites]: the app modules sit one level up
// and import the app's i18n Locale type, which the site does not have.
const FILES = [
  ['src/data/company.ts', 'src/data/company.ts', []],
  [
    'src/data/legal.ts',
    'src/data/legal/app.ts',
    [
      ["from './company'", "from '../company'"],
      ["import type { Locale } from '../i18n';", "type Locale = 'en' | 'fi';"],
      ["from './legal.fi'", "from './app.fi'"],
    ],
  ],
  [
    'src/data/legal.fi.ts',
    'src/data/legal/app.fi.ts',
    [
      ["from './company'", "from '../company'"],
      ["from './legal'", "from './app'"],
    ],
  ],
]

for (const [source, target, rewrites] of FILES) {
  let text = await readFile(resolve(app, source), 'utf8')
  for (const [from, to] of rewrites) {
    if (!text.includes(from)) throw new Error(`${source}: expected "${from}" - the app file changed shape`)
    text = text.replace(from, to)
  }
  // company.ts stays byte-identical across PK, STR and the site
  if (target !== 'src/data/company.ts') text = HEADER + text
  await writeFile(resolve(root, target), text)
  console.log(`${source} -> ${target}`)
}
